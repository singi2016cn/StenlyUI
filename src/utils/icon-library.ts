// 图标缓存
const iconCache = new Map<string, string>();

// 是否禁用缺失图标警告
let warnMissingIcons = true;

/**
 * 注册图标
 * @param name 图标名称
 * @param svgContent SVG 内容
 */
export function registerIcon(name: string, svgContent: string): void {
  iconCache.set(name, normalizeSvg(svgContent));
}

/**
 * 批量注册图标
 * @param icons 图标对象 { name: svgContent }
 */
export function registerIcons(icons: Record<string, string>): void {
  Object.entries(icons).forEach(([name, svg]) => {
    registerIcon(name, svg);
  });
}

/**
 * 获取图标 SVG
 * @param name 图标名称
 * @returns SVG 内容
 */
export function getIconSvg(name: string): string | null {
  if (!name) {
    return null;
  }

  // 检查替换映射
  const replacementName = ICON_REPLACEMENTS[name];
  const actualName = replacementName || name;

  // 从缓存获取
  const cached = iconCache.get(actualName);
  if (cached) {
    return cached;
  }

  // 尝试从预定义的图标库获取
  const svg = getPredefinedIcon(actualName);
  if (svg) {
    iconCache.set(actualName, svg);
    return svg;
  }

  // 警告缺失图标
  if (warnMissingIcons && process.env.NODE_ENV === 'development') {
    console.warn(`图标 "${name}" 未在图标库中注册`);
  }

  return null;
}

/**
 * 检查图标是否存在
 * @param name 图标名称
 * @returns 是否存在
 */
export function isExistingIcon(name: string): boolean {
  const actualName = ICON_REPLACEMENTS[name] || name;
  return iconCache.has(actualName) || getPredefinedIcon(actualName) !== null;
}

/**
 * 替换图标映射
 * @param source 原图标名称
 * @param destination 目标图标名称
 */
export function replaceIcon(source: string, destination: string): void {
  ICON_REPLACEMENTS[source] = destination;
}

/**
 * 禁用缺失图标警告
 */
export function disableMissingIconWarning(): void {
  warnMissingIcons = false;
}

/**
 * 启用缺失图标警告
 */
export function enableMissingIconWarning(): void {
  warnMissingIcons = true;
}

/**
 * 转换图标类名（兼容 Font Awesome 类名）
 * @param icon Font Awesome 类名
 * @returns 转换后的图标名称
 */
export function convertIconClass(icon: string): string {
  return icon
    .replace(/far\s+fa-/g, 'far-')
    .replace(/fab\s+fa-/g, 'fab-')
    .replace(/fas\s+fa-/g, '')
    .replace(/fa-/g, '')
    .trim();
}

/**
 * 规范化 SVG 内容
 */
function normalizeSvg(svg: string): string {
  let normalized = svg.trim();

  // 如果已经是完整的 SVG，提取 viewBox 和 path
  if (normalized.startsWith('<svg')) {
    const viewBoxMatch = normalized.match(/viewBox="([^"]+)"/);
    const pathMatch = normalized.match(/<path[^>]*d="([^"]+)"[^>]*>/);

    if (viewBoxMatch && pathMatch) {
      return `<svg viewBox="${viewBoxMatch[1]}"><path d="${pathMatch[1]}"/></svg>`;
    }
  }

  return normalized;
}

/**
 * 获取预定义图标（使用简化的 SVG 路径）
 */
function getPredefinedIcon(name: string): string | null {
  const icon = PREDEFINED_ICONS[name as keyof typeof PREDEFINED_ICONS];
  if (icon) {
    return `<svg viewBox="${icon.viewBox}"><path d="${icon.path}"/></svg>`;
  }
  return null;
}

